/*
═══════════════════════════════════════════════════════════════
1. JAVASCRIPT-ის მიმოხილვა (AN OVERVIEW OF JAVASCRIPT)
═══════════════════════════════════════════════════════════════

JavaScript არის მაღალი დონის, პროტოტიპებზე დაფუძნებული
ობიექტზე ორიენტირებული, მულტი-პარადიგმური, ინტერპრეტირებული
ან JIT კომპილირებული, დინამიკური, ერთნაკადიანი, ნაგვის
შემგროვებელი პროგრამირების ენა, პირველი კლასის ფუნქციებით
და არა-ბლოკირებადი event loop კონკურენტული მოდელით.

მოდით, თითოეული მახასიათებელი დეტალურად განვიხილოთ:
*/

// მაღალი დონის (HIGH-LEVEL)
// რესურსების (მეხსიერების) მართვა ხელით არ გვიწევს.
// ყველაფერი ავტომატურად ხდება. ეს ენას უფრო ადვილს ხდის
// სწავლასა და გამოყენებაში, მაგრამ პროგრამები ვერასოდეს
// იქნება ისეთი სწრაფი, როგორც დაბალი დონის C/C++ პროგრამები.

// ნაგვის შემგროვებელი (GARBAGE-COLLECTED)
// ნაგვის ავტომატური შეგროვების მექანიზმი, რომელიც წაშლის ძველ,
// გამოუყენებელ ობიექტებს მეხსიერებიდან. მეხსიერების მართვა ხელით არ გვიწევს.

// ინტერპრეტირებული ან JIT კომპილირებული (INTERPRETED OR JIT COMPILED)
// JavaScript ადრე წმინდა ინტერპრეტირებული იყო, მაგრამ თანამედროვე
// ძრავები JIT კომპილაციას იყენებენ უკეთესი წარმადობისთვის.
// (დეტალურად მე-3 სექციაში)

// მულტი-პარადიგმური (MULTI-PARADIGM)
// JavaScript მხარს უჭერს მრავალ პროგრამირების პარადიგმას:
// - პროცედურული პროგრამირება (კოდის ხაზობრივი ორგანიზება)
// - ობიექტზე ორიენტირებული პროგრამირება (OOP)
// - ფუნქციონალური პროგრამირება (FP)
// შეგვიძლია ავირჩიოთ რომელ მიდგომას გამოვიყენებთ, ან შევურიოთ ერთმანეთს.

// პროტოტიპებზე დაფუძნებული ობიექტზე ორიენტირებული (PROTOTYPE-BASED OOP)
// JavaScript-ში თითქმის ყველაფერი ობიექტია (პრიმიტივების გარდა).
// მაგალითად, მასივები ობიექტებია. ამიტომ შეგვიძლია გამოვიყენოთ
// push, pop და სხვა მეთოდები. ისინი აგებულია პროტოტიპიდან,
// რომელიც შეიცავს ყველა მასივის მეთოდს.

// პირველი კლასის ფუნქციები (FIRST-CLASS FUNCTIONS)
// ფუნქციები განიხილება როგორც ჩვეულებრივი ცვლადები.
// შეგვიძლია სხვა ფუნქციებში გადავცეთ, ფუნქციებიდან დავაბრუნოთ
// და ცვლადებში შევინახოთ. ეს ფუნქციონალურ პროგრამირებას შესაძლებელს ხდის.
const greet = () => console.log('Hey!');
const btnEl = { addEventListener: (event, fn) => fn() };
btnEl.addEventListener('click', greet);

// დინამიკური (DYNAMIC)
// JavaScript დინამიკურად ტიპიზირებულია. ცვლადებს მონაცემთა ტიპს
// არ მივანიჭებთ. ტიპები ავტომატურად განისაზღვრება გაშვებისას
// და შეიძლება შეიცვალოს ცვლადის ხელახალი მინიჭებისას.
let x = 23;     // x არის რიცხვი
x = 'hello';    // ახლა x არის სტრინგი — შეცდომა არ არის!

// ერთნაკადიანი (SINGLE-THREADED)
// JavaScript ერთ ნაკადში მუშაობს, ამიტომ ერთდროულად
// მხოლოდ ერთი რამის გაკეთება შეუძლია.

// არა-ბლოკირებადი Event Loop (NON-BLOCKING EVENT LOOP)
// ხანგრძლივი ამოცანები (მაგ. მონაცემების წამოღება) "ფონზე" სრულდება
// Web API-ების გამოყენებით. Event loop იღებს დასრულებულ ამოცანებს
// callback queue-დან და call stack-ში ათავსებს შესასრულებლად.
// ასე უმკლავდება JavaScript კონკურენტულობას, მიუხედავად იმისა, რომ ერთნაკადიანია.


/*
═══════════════════════════════════════════════════════════════
2. JAVASCRIPT ძრავი (THE JAVASCRIPT ENGINE)
═══════════════════════════════════════════════════════════════

JavaScript ძრავი არის პროგრამა, რომელიც ასრულებს JavaScript კოდს.
ყველა ბრაუზერს აქვს თავისი ძრავი.
*/

// ყველაზე ცნობილი ძრავი: V8 Engine
// - მუშაობს Google Chrome-სა და Node.js-ში
// სხვა ძრავები:
// - SpiderMonkey (Firefox)
// - JavaScriptCore / Nitro (Safari)
// - Chakra / ახლა V8 (Edge)

// ყველა JavaScript ძრავს აქვს ორი მთავარი კომპონენტი:

// 1. CALL STACK (გამოძახებების სტეკი)
//    სადაც ჩვენი კოდი რეალურად სრულდება, execution context-ების გამოყენებით.
//    წარმოიდგინეთ როგორც "ყუთების" სტეკი — ყოველი ყუთი ერთი ფუნქციის გამოძახებაა.

// 2. HEAP (გროვა)
//    სადაც ობიექტები ინახება მეხსიერებაში. ეს არის არასტრუქტურირებული
//    მეხსიერების პული, რომელიც ინახავს ყველა ობიექტს, რაც ჩვენს პროგრამას სჭირდება.

// ვიზუალური წარმოდგენა:
// ┌─────────────────────────────────────┐
// │           JS ძრავი                  │
// │  ┌──────────────┐ ┌──────────────┐  │
// │  │              │ │    ■  ●      │  │
// │  │  ▬▬▬▬▬▬▬▬▬▬  │ │  ▲  ◆       │  │
// │  │  ▬▬▬▬▬▬▬▬▬▬  │ │     ■  ●    │  │
// │  │  ▬▬▬▬▬▬▬▬▬▬  │ │  ◆     ▲    │  │
// │  │              │ │       ■      │  │
// │  │  CALL STACK  │ │    HEAP      │  │
// │  └──────────────┘ └──────────────┘  │
// └─────────────────────────────────────┘


/*
═══════════════════════════════════════════════════════════════
3. კომპილაცია vs. ინტერპრეტაცია (COMPILATION VS. INTERPRETATION)
═══════════════════════════════════════════════════════════════

როგორ გარდაიქმნება სორს კოდი მანქანურ კოდად (0-ები და 1-ები),
რომელიც კომპიუტერს ესმის?
*/

// === კომპილაცია (COMPILATION) ===
// მთელი სორს კოდი ერთდროულად გარდაიქმნება მანქანურ კოდად
// და იწერება პორტატულ ბინარულ ფაილში.
// ბინარული ფაილის გაშვება მოგვიანებით შეიძლება — ბევრი ხნის შემდეგაც კი.
//
// ნაბიჯი 1: სორს კოდი → კომპილაცია → პორტატული ფაილი (მანქანური კოდი)
// ნაბიჯი 2: პორტატული ფაილი → შესრულება → პროგრამა მუშაობს
//
// მთავარი: შესრულება კომპილაციიდან ბევრი ხნის შემდეგ შეიძლება მოხდეს.

// === ინტერპრეტაცია (INTERPRETATION) ===
// ინტერპრეტატორი გადის სორს კოდს და ხაზ-ხაზ ასრულებს.
// კოდი მაინც უნდა გარდაიქმნას მანქანურ კოდად, მაგრამ ეს ხდება
// ყოველი ხაზის შესრულებამდე. ცალკე კომპილაციის ეტაპი არ არის.
//
// ნაბიჯი 1: სორს კოდი → ხაზ-ხაზ შესრულება → პროგრამა მუშაობს
//
// პრობლემა: გაცილებით ნელია, ვიდრე კომპილირებული კოდი.

// === JIT კომპილაცია (JUST-IN-TIME COMPILATION) ===
// მთელი კოდი ერთდროულად გარდაიქმნება მანქანურ კოდად
// და შემდეგ დაუყოვნებლივ სრულდება.
// ჩვეულებრივი კომპილაციისგან განსხვავებით, პორტატული ფაილი არ იქმნება —
// მანქანური კოდი დისკზე არ იწერება.
// სწორედ ამას იყენებენ თანამედროვე JavaScript ძრავები!
//
// ნაბიჯი 1: სორს კოდი → კომპილაცია → მანქანური კოდი (არა პორტატული ფაილი)
// ნაბიჯი 2: მანქანური კოდი → შესრულება → პროგრამა მუშაობს (ხდება დაუყოვნებლივ)
//
// მთავარი: აერთიანებს კომპილაციის სისწრაფეს და ინტერპრეტაციის მოხერხებულობას.


/*
═══════════════════════════════════════════════════════════════
4. JAVASCRIPT-ის თანამედროვე JIT კომპილაცია
   (MODERN JIT COMPILATION OF JAVASCRIPT)
═══════════════════════════════════════════════════════════════

როცა JavaScript კოდი ძრავში შედის, შემდეგი ეტაპები სრულდება:
*/

// ნაბიჯი 1: პარსინგი (PARSING)
// კოდი იპარსება (იკითხება) მონაცემთა სტრუქტურაში, რომელსაც AST ეწოდება
// (Abstract Syntax Tree — აბსტრაქტული სინტაქსის ხე).
// კოდის ყოველი ხაზი იყოფა მნიშვნელოვან ნაწილებად
// (მაგ. const, ცვლადის სახელები, მნიშვნელობები)
// და ინახება ხის სტრუქტურაში. აქვე მოწმდება სინტაქსური შეცდომები.
//
// შენიშვნა: AST-ს DOM ხესთან კავშირი არ აქვს!

// AST-ის მაგალითი:
// const x = 23;
//
// VariableDeclaration {
//   kind: "const",
//   declarations: [
//     VariableDeclarator {
//       id: Identifier { name: "x" },
//       init: Literal { value: 23, raw: "23" }
//     }
//   ]
// }

// ნაბიჯი 2: კომპილაცია (COMPILATION)
// AST კომპილდება მანქანურ კოდად (JIT კომპილაცია).

// ნაბიჯი 3: შესრულება (EXECUTION)
// მანქანური კოდი დაუყოვნებლივ სრულდება Call Stack-ში.

// ნაბიჯი 4: ოპტიმიზაცია (OPTIMIZATION)
// თანამედროვე ძრავები თავდაპირველად ქმნიან მანქანური კოდის
// არაოპტიმიზირებულ ვერსიას, რათა შესრულება რაც შეიძლება
// სწრაფად დაიწყოს. შემდეგ, ფონზე, კოდი თავიდან კომპილდება
// და ოპტიმიზდება შესრულებისას. ეს სპეციალურ ნაკადებში ხდება,
// რომლებზეც კოდიდან წვდომა არ გვაქვს. ოპტიმიზაციის ციკლი
// შეიძლება რამდენჯერმე გამეორდეს.

// მნიშვნელოვანი: "JavaScript ინტერპრეტირებული ენაა" — ეს აღარ არის ზუსტი!
// თანამედროვე JavaScript JIT კომპილაციას იყენებს, არა წმინდა ინტერპრეტაციას.


/*
═══════════════════════════════════════════════════════════════
5. JAVASCRIPT RUNTIME გარემო (THE JAVASCRIPT RUNTIME)
═══════════════════════════════════════════════════════════════

JavaScript runtime არის "კონტეინერი", რომელიც მოიცავს ყველაფერს,
რაც საჭიროა JavaScript კოდის შესასრულებლად.
ყველაზე გავრცელებული runtime ბრაუზერია.
*/

// JavaScript Runtime ბრაუზერში შედგება:

// ┌────────────────────────────────────────────────────────┐
// │          JS RUNTIME ბრაუზერში                          │
// │                                                        │
// │  ┌─────────────────────┐  ┌─────────────────────────┐  │
// │  │     JS ძრავი        │  │       WEB APIs           │  │
// │  │  ┌──────┐ ┌──────┐  │  │  ┌─────┐  ┌──────┐     │  │
// │  │  │CALL  │ │      │  │  │  │ DOM │  │Timers│     │  │
// │  │  │STACK │ │ HEAP │  │  │  ├─────┤  ├──────┤     │  │
// │  │  │      │ │      │  │  │  │Fetch│  │ ...  │     │  │
// │  │  └──────┘ └──────┘  │  │  └─────┘  └──────┘     │  │
// │  └─────────────────────┘  └─────────────────────────┘  │
// │                                                        │
// │  ┌──────────────────────────────────────────────────┐   │
// │  │ CALLBACK QUEUE:  click │ timer │ data │ ...      │   │
// │  └──────────────────────────────────────────────────┘   │
// │         ↑  EVENT LOOP  ↓                               │
// └────────────────────────────────────────────────────────┘

// 1. JS ძრავი (Call Stack + Heap)
// Runtime-ის გული. აქ სრულდება კოდი (Call Stack)
