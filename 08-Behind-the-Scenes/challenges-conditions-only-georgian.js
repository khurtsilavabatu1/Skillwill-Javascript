// სავარჯიშო ჩელენჯი #3 - Hoisting-ის თავსატეხები
// (Hoisting + TDZ)

/*
იწინასწარმეტყველეთ და გადაამოწმეთ რა ხდება, როცა ცვლადებსა და
ფუნქციებს მათი გამოცხადების წინ იყენებთ.

1. ნებისმიერი გამოცხადების წინ სცადეთ:
   a) გამოიძახეთ function declaration 'greetDecl' — იმუშავებს?
   b) დალოგეთ var ცვლადი 'myVar' — რა მნიშვნელობა ექნება?
   c) დალოგეთ let ცვლადი 'myLet' — რა მოხდება?
   d) გამოიძახეთ const-ში შენახული function expression 'greetExpr' — რა მოხდება?
2. ახლა გამოაცხადეთ ყველა:
   a) function greetDecl() { return 'Hello from declaration!'; }
   b) var myVar = 'I am var';
   c) let myLet = 'I am let';
   d) const greetExpr = function() { return 'Hello from expression!'; };
3. გამოცხადებების შემდეგ, კვლავ გამოიძახეთ/დალოგეთ ყველაფერი დასადასტურებლად
4. დაწერეთ კომენტარები, რომლებიც ხსნიან რატომ იქცევა თითოეული განსხვავებულად გამოცხადებამდე

მინიშნება: Function declaration-ები სრულად არის hoisted (გამოძახება შესაძლებელია გამოცხადებამდე)
მინიშნება: var არის hoisted როგორც undefined
მინიშნება: let/const არის TDZ-ში (Temporal Dead Zone) მათი გამოცხადების ხაზამდე

წარმატებები 😀
*/


